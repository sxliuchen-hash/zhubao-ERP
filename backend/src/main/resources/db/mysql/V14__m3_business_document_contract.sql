CREATE TABLE IF NOT EXISTS biz_mother_order (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    code VARCHAR(80) NOT NULL,
    customer_id BIGINT NOT NULL,
    owner_customer_id BIGINT,
    material_code VARCHAR(80) NOT NULL,
    inbound_date VARCHAR(20),
    inbound_express_company VARCHAR(80),
    inbound_express_no VARCHAR(80),
    sender_name_snapshot VARCHAR(120),
    receiver_name_snapshot VARCHAR(120),
    unpack_signer_name VARCHAR(120),
    goods_name_snapshot VARCHAR(160),
    owner_type VARCHAR(20) NOT NULL,
    is_customer_owned BOOLEAN NOT NULL DEFAULT TRUE,
    warehouse_code VARCHAR(50) NOT NULL,
    quantity DECIMAL(18,3) NOT NULL,
    quantity_unit VARCHAR(20) NOT NULL DEFAULT '件',
    weight DECIMAL(18,3) NOT NULL,
    stock_status VARCHAR(40) NOT NULL,
    ledger_code VARCHAR(80) NOT NULL,
    source_register_type VARCHAR(64),
    source_line_no INT,
    source_sequence_no VARCHAR(40),
    operator VARCHAR(80) NOT NULL,
    evidence_code VARCHAR(120),
    inbound_remark TEXT,
    order_status VARCHAR(40) NOT NULL,
    created_at VARCHAR(40) NOT NULL,
    created_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uk_mother_order_code (code),
    UNIQUE KEY uk_mother_order_ledger (ledger_code),
    KEY idx_mother_order_customer (customer_id),
    KEY idx_mother_order_courier (inbound_express_no),
    KEY idx_mother_order_source (source_register_type, source_line_no)
);

CREATE TABLE IF NOT EXISTS biz_mother_order_item (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    mother_order_code VARCHAR(80) NOT NULL,
    material_code VARCHAR(80) NOT NULL,
    quantity DECIMAL(18,3) NOT NULL,
    quantity_unit VARCHAR(20) NOT NULL DEFAULT '件',
    weight DECIMAL(18,3) NOT NULL,
    weight_unit VARCHAR(20) NOT NULL DEFAULT 'g',
    ledger_code VARCHAR(80) NOT NULL,
    created_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    KEY idx_mother_order_item_mother (mother_order_code),
    KEY idx_mother_order_item_material (material_code),
    CONSTRAINT fk_mother_order_item_mother
        FOREIGN KEY (mother_order_code) REFERENCES biz_mother_order(code)
);

CREATE TABLE IF NOT EXISTS biz_outbound_order (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    code VARCHAR(80) NOT NULL,
    mother_order_code VARCHAR(80) NOT NULL,
    work_order_code VARCHAR(90) NOT NULL,
    customer_id BIGINT NOT NULL,
    owner_customer_id BIGINT,
    material_code VARCHAR(80) NOT NULL,
    from_warehouse_code VARCHAR(50) NOT NULL,
    to_warehouse_code VARCHAR(50) NOT NULL,
    delivery_date VARCHAR(20),
    delivery_category VARCHAR(80),
    delivery_quantity DECIMAL(18,3) NOT NULL,
    delivery_quantity_unit VARCHAR(20) NOT NULL DEFAULT '件',
    delivery_weight DECIMAL(18,3) NOT NULL,
    express_company VARCHAR(80),
    express_no VARCHAR(80) NOT NULL,
    logistics_raw_text VARCHAR(160),
    handler_name_snapshot VARCHAR(120),
    source_register_type VARCHAR(64),
    source_line_no INT,
    source_sequence_no VARCHAR(40),
    operator VARCHAR(80) NOT NULL,
    evidence_code VARCHAR(120),
    outbound_remark TEXT,
    order_status VARCHAR(40) NOT NULL,
    ledger_code VARCHAR(80) NOT NULL,
    created_at VARCHAR(40) NOT NULL,
    created_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uk_outbound_order_code (code),
    UNIQUE KEY uk_outbound_order_ledger (ledger_code),
    KEY idx_outbound_order_customer (customer_id),
    KEY idx_outbound_order_logistics (express_no),
    KEY idx_outbound_order_mother (mother_order_code),
    KEY idx_outbound_order_source (source_register_type, source_line_no)
);

CREATE TABLE IF NOT EXISTS biz_outbound_order_item (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    outbound_order_code VARCHAR(80) NOT NULL,
    mother_order_code VARCHAR(80) NOT NULL,
    work_order_code VARCHAR(90) NOT NULL,
    material_code VARCHAR(80) NOT NULL,
    quantity DECIMAL(18,3) NOT NULL,
    quantity_unit VARCHAR(20) NOT NULL DEFAULT '件',
    weight DECIMAL(18,3) NOT NULL,
    weight_unit VARCHAR(20) NOT NULL DEFAULT 'g',
    ledger_code VARCHAR(80) NOT NULL,
    created_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    KEY idx_outbound_order_item_outbound (outbound_order_code),
    KEY idx_outbound_order_item_mother (mother_order_code),
    KEY idx_outbound_order_item_work_order (work_order_code),
    CONSTRAINT fk_outbound_order_item_outbound
        FOREIGN KEY (outbound_order_code) REFERENCES biz_outbound_order(code)
);
