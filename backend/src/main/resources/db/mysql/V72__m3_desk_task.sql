-- 工作台轻任务。建模、设计等事项只记录指派和完成，不写工序、库存、质检或发货。
create table biz_desk_task (
    task_code varchar(40) not null primary key,
    kind varchar(16) not null,
    title varchar(80) not null,
    note varchar(500) not null default '',
    customer_id bigint null,
    customer_name varchar(120) not null default '',
    mother_order_code varchar(40) not null default '',
    assignee_username varchar(64) not null,
    assignee_name varchar(80) not null default '',
    due_date char(10) not null,
    task_status varchar(16) not null,
    creator_username varchar(64) not null,
    created_at varchar(40) not null,
    request_id varchar(80) not null,
    version int not null,
    completed_at varchar(40) not null default '',
    completed_by varchar(64) not null default '',
    result_note varchar(500) not null default '',
    complete_request_id varchar(80) null,
    cancelled_at varchar(40) not null default '',
    cancelled_by varchar(64) not null default '',
    cancel_reason varchar(500) not null default '',
    cancel_request_id varchar(80) null,
    unique key uk_desk_task_request (request_id),
    unique key uk_desk_task_complete_request (complete_request_id),
    unique key uk_desk_task_cancel_request (cancel_request_id),
    key idx_desk_task_assignee (assignee_username, task_status),
    key idx_desk_task_creator (creator_username, task_status)
);
