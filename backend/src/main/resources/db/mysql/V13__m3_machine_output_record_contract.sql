CREATE TABLE IF NOT EXISTS biz_machine_output_record (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    code VARCHAR(60) NOT NULL,
    work_date VARCHAR(20) NOT NULL,
    customer_id BIGINT,
    customer_name_snapshot VARCHAR(120),
    product_category VARCHAR(120) NOT NULL,
    machine_id BIGINT,
    machine_no_snapshot VARCHAR(80) NOT NULL,
    work_order_code VARCHAR(80),
    work_process_id BIGINT,
    work_report_code VARCHAR(80),
    output_quantity DECIMAL(18,3) NOT NULL,
    quantity_unit VARCHAR(20) NOT NULL DEFAULT '件',
    operator_employee_id BIGINT,
    operator_signature_name VARCHAR(120) NOT NULL,
    signature_media_id BIGINT,
    source_register_type VARCHAR(64),
    source_line_no INT,
    machine_line_no VARCHAR(40),
    source_sequence_no VARCHAR(40),
    import_batch_no VARCHAR(96),
    ledger_code VARCHAR(80),
    output_status VARCHAR(40) NOT NULL DEFAULT 'SUBMITTED',
    remark TEXT,
    created_by VARCHAR(80) NOT NULL,
    created_at VARCHAR(40) NOT NULL,
    created_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uk_machine_output_code (code),
    KEY idx_machine_output_work_date (work_date),
    KEY idx_machine_output_machine (machine_no_snapshot),
    KEY idx_machine_output_import_batch (import_batch_no),
    KEY idx_machine_output_work_order (work_order_code)
);
