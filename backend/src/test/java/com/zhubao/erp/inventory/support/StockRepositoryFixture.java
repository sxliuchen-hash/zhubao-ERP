package com.zhubao.erp.inventory.support;

import com.zhubao.erp.inventory.domain.StockLedgerRepository;
import com.zhubao.erp.inventory.infra.InMemoryStockLedgerRepository;
import com.zhubao.erp.inventory.infra.JdbcStockLedgerRepository;
import org.h2.jdbcx.JdbcDataSource;
import org.springframework.core.io.ClassPathResource;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;

/**
 * 共用库存契约场景使用旧版表结构与实际增量迁移，避免手写新列掩盖迁移问题。
 */
public final class StockRepositoryFixture {

    private StockRepositoryFixture() {
    }

    public static StockLedgerRepository create(boolean jdbc) throws SQLException {
        return jdbc ? new JdbcStockLedgerRepository(jdbcDataSource()) : new InMemoryStockLedgerRepository();
    }

    public static JdbcDataSource jdbcDataSource() throws SQLException {
        JdbcDataSource dataSource = legacyJdbcDataSource();
        migrateSourceWorkOrder(dataSource);
        return dataSource;
    }

    public static void migrateSourceWorkOrder(JdbcDataSource dataSource) throws SQLException {
        try (var resource = new ClassPathResource("db/mysql/V39__m3_inventory_source_work_order.sql").getInputStream();
             Connection connection = dataSource.getConnection();
             Statement statement = connection.createStatement()) {
            String sql = new String(resource.readAllBytes(), StandardCharsets.UTF_8).replaceAll("(?m)^--.*$", "");
            for (String command : sql.split(";")) {
                if (!command.isBlank()) {
                    statement.execute(command);
                }
            }
        } catch (IOException ex) {
            throw new IllegalStateException("无法读取库存来源工单迁移", ex);
        }
    }

    public static JdbcDataSource legacyJdbcDataSource() throws SQLException {
        JdbcDataSource dataSource = new JdbcDataSource();
        dataSource.setURL("jdbc:h2:mem:inventory_" + System.nanoTime() + ";MODE=MySQL;DB_CLOSE_DELAY=-1");
        dataSource.setUser("sa");
        dataSource.setPassword("");
        try (Connection connection = dataSource.getConnection();
             Statement statement = connection.createStatement()) {
            statement.execute("""
                    create table inv_stock_ledger (
                        id bigint generated by default as identity primary key,
                        code varchar(60) not null unique,
                        biz_time timestamp(3) not null,
                        document_type varchar(50) not null,
                        document_code varchar(80) not null,
                        owner_type varchar(20) not null,
                        owner_customer_id bigint null,
                        customer_id bigint null,
                        mother_order_code varchar(80) not null,
                        work_order_code varchar(90) null,
                        material_code varchar(80) not null,
                        quantity decimal(18,3) not null,
                        weight decimal(18,3) not null,
                        from_warehouse_code varchar(50) null,
                        to_warehouse_code varchar(50) not null,
                        from_stock_status varchar(30) null,
                        to_stock_status varchar(30) not null,
                        remark varchar(500) null,
                        created_at timestamp(3) not null default current_timestamp
                    )
                    """);
            statement.execute("""
                    create table inv_stock_balance (
                        id bigint generated by default as identity primary key,
                        owner_type varchar(20) not null,
                        owner_customer_id bigint null,
                        customer_id bigint null,
                        mother_order_code varchar(80) not null,
                        work_order_code varchar(90) null,
                        material_code varchar(80) not null,
                        warehouse_code varchar(50) not null,
                        stock_status varchar(30) not null,
                        dimension_key varchar(500) not null unique,
                        available_quantity decimal(18,3) not null default 0,
                        available_weight decimal(18,3) not null default 0,
                        last_ledger_code varchar(60) null,
                        updated_at timestamp(3) not null default current_timestamp
                    )
                    """);
        }
        return dataSource;
    }
}
