import { mount, flushPromises } from '@vue/test-utils';
import { expect, it, vi } from 'vitest';
import FactoryOperationsWorkspace from './FactoryOperationsWorkspace.vue';
import { apiGet, apiPost, setAuthToken } from '../../services/apiClient';
vi.mock('../../services/apiClient', async () => ({ ...await vi.importActual<typeof import('../../services/apiClient')>('../../services/apiClient'), apiGet: vi.fn(), apiPost: vi.fn() }));
it('读取实际物品批次库位办理领用，重开后仍用原请求和原版本，不因库存变化重复提交', async () => {
  setAuthToken('factory-native-replay');
  const item = { itemId: 'ITEM-A', category: 'BEAD', materialName: '自有珠料', specCode: '8mm', unit: '颗', consumptionTiming: 'UNDECIDED', custodyMode: 'UNDECIDED', version: 3 };
  const position = { item, balances: [{ batchCode: 'BATCH-REAL', warehouseCode: 'WH-REAL', quantity: 100, unit: '颗', weight: { state: 'UNKNOWN', value: null } }], receipts: [], issues: [], loans: [], pieces: [], toolQuantity: null };
  vi.mocked(apiGet).mockImplementation(async path => path === '/api/inventory/factory-items' ? [item] : position);
  vi.mocked(apiPost).mockRejectedValueOnce(new Error('响应丢失')).mockResolvedValue({ issueId: 'ISS-REAL' });
  let view = mount(FactoryOperationsWorkspace); await flushPromises();
  await view.get('select').setValue('ITEM-A'); await flushPromises();
  expect(view.text()).toContain('BATCH-REAL'); expect(view.text()).toContain('重量待核'); expect(view.text()).not.toContain('WS01');
  const field = (text: string) => view.findAll('label').find(row => row.text().startsWith(text))!;
  await field('办理').get('select').setValue('issue');
  await field('库位').get('input').setValue('WH-REAL'); await field('来源批次').get('select').setValue('BATCH-REAL');
  await field('车间').get('input').setValue('WORKSHOP-REAL'); await field('本次数量').get('input').setValue('12');
  await view.findAll('button').find(row => row.text() === '提交本次办理')!.trigger('click'); await flushPromises();
  const original = vi.mocked(apiPost).mock.calls[0];
  expect(original).toEqual(['/api/inventory/company-material-issues', expect.objectContaining({ itemId: 'ITEM-A', batchCode: 'BATCH-REAL', fromWarehouse: 'WH-REAL', workshopCode: 'WORKSHOP-REAL', quantity: '12', weight: null })]);
  view.unmount(); view = mount(FactoryOperationsWorkspace); await flushPromises();
  await view.get('select').setValue('ITEM-A'); await flushPromises();
  await view.findAll('button').find(row => row.text() === '原请求重试')!.trigger('click'); await flushPromises();
  expect(vi.mocked(apiPost).mock.calls[1]).toEqual(original);
  await view.findAll('button').find(row => row.text() === '开始下一笔')!.trigger('click'); await flushPromises();
  await view.findAll('button').find(row => row.text() === '提交本次办理')!.trigger('click'); await flushPromises();
  expect(vi.mocked(apiPost).mock.calls[2][1]).toEqual(expect.objectContaining({ quantity: '12' }));
  expect((vi.mocked(apiPost).mock.calls[2][1] as { requestId: string }).requestId).not.toBe((original[1] as { requestId: string }).requestId);
  view.unmount();
});
