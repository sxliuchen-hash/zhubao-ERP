import { mount, flushPromises } from '@vue/test-utils';
import { ref } from 'vue';
import { expect, it, vi } from 'vitest';
import DeliveryWorkspace from './DeliveryWorkspace.vue';
import { fetchProductionTarget, finishBagStock } from '../../services/productionQualityApi';
import { fetchDelivery, fetchDeliveryImpact, openDelivery, confirmDelivery, publishDelivery } from '../../services/deliveryApi';
import { renderQrSvg } from '../../services/qrcode';
import { setAuthToken } from '../../services/apiClient';
vi.mock('../../services/productionQualityApi', () => ({ fetchProductionTarget: vi.fn(), finishBagStock: vi.fn() }));
vi.mock('../../services/deliveryApi', () => ({ fetchDelivery: vi.fn(), fetchDeliveryImpact: vi.fn(), openDelivery: vi.fn(), confirmDelivery: vi.fn(), publishDelivery: vi.fn(), disableDeliveryLink: vi.fn(), fetchDeliveryLabel: vi.fn(), correctDelivery: vi.fn(), receiveDeliveryReturn: vi.fn() }));
it('实际袋先形成成品再确认独立发货，丢失响应按原请求恢复，A5实际打印不再出库', async () => {
  setAuthToken('shipping-native-retry');
  const draft = { deliveryId: 'FH-NATIVE', customerId: 7, version: 1, status: 'DRAFT', logisticsNote: '', remark: '' };
  const line = { deliveryId: draft.deliveryId, lineNo: 1, bagId: 'BAG-REAL', bagVersion: 8, targetCode: 'MD-REAL', quantity: 480, quantityUnit: '颗', materialCode: '牙骨', customerName: '客户甲', goodsSpecification: '8mm', processingSummary: '抛光后穿串', weight: { state: 'KNOWN', value: 9.4 } };
  vi.mocked(fetchProductionTarget).mockResolvedValue({ targetCode: 'MD-REAL', customerId: 7, quantityUnit: '颗', requirement: '', defaultSteps: [], route: null, bags: [{ bag: { id: 'BAG-REAL', targetCode: 'MD-REAL', version: 8, quantity: 480, materialCode: '牙骨', requirementVersion: 'REQ-A', sourceKey: 'LINE-A', weight: line.weight }, availability: {} as never, shippable: { quantity: 480, blockingReasons: [] } as never }] });
  vi.mocked(finishBagStock).mockResolvedValue({});
  vi.mocked(openDelivery).mockResolvedValueOnce({ draft }).mockResolvedValueOnce({ draft: { ...draft, version: 2, status: 'CONFIRMED' } });
  vi.mocked(confirmDelivery).mockRejectedValueOnce(new Error('响应丢失'));
  vi.mocked(fetchDelivery).mockResolvedValue({ draft: { ...draft, status: 'CONFIRMED' }, lines: [line], sources: [{ lineNo: 1, outboundCode: 'CK-A', quantity: 480, weight: 9.4 }], returns: [] });
  vi.mocked(fetchDeliveryImpact).mockResolvedValue({ confirmedChargeRecord: '无', confirmedRefundRecord: '待核' });
  const popup = { opener: {}, document: { open: vi.fn(), write: vi.fn(), close: vi.fn(), fonts: { ready: Promise.resolve() }, title: '' }, focus: vi.fn(), print: vi.fn() };
  vi.spyOn(window, 'open').mockReturnValue(popup as unknown as Window);
  const view = mount(DeliveryWorkspace, { props: { initialTarget: 'MD-REAL' }, global: { provide: { 'zhubao-auth-session': ref({ role: 'ADMIN', effectivePermissions: ['BUSINESS_OUTBOUND_SHIPMENT', 'LABEL_PRINT'] }) } } });
  const button = (text: string) => view.findAll('button').find(row => row.text() === text)!;
  await button('读取可发袋').trigger('click'); await flushPromises();
  await view.get('[aria-label="选择BAG-REAL"]').setValue(true);
  await view.get('[aria-label="已核对所选袋"]').setValue(true);
  await button('确认发货').trigger('click'); await flushPromises();
  expect(view.text()).toContain('响应丢失');
  await button('原请求重试').trigger('click'); await flushPromises();
  expect(vi.mocked(finishBagStock).mock.calls[1]).toEqual(vi.mocked(finishBagStock).mock.calls[0]);
  expect(vi.mocked(openDelivery).mock.calls[1]).toEqual(vi.mocked(openDelivery).mock.calls[0]);
  expect(openDelivery).toHaveBeenCalledWith(expect.objectContaining({ selections: [{ bagId: 'BAG-REAL', bagVersion: 8, targetCode: 'MD-REAL', quantityUnit: '颗' }] }));
  expect(confirmDelivery).toHaveBeenCalledTimes(1);
  const token = 'b'.repeat(64); vi.mocked(publishDelivery).mockResolvedValue(token);
  await button('生成本次交付扫码链接').trigger('click'); await flushPromises();
  await button('用办公打印机打印A5').trigger('click'); await flushPromises();
  expect(popup.print).toHaveBeenCalledOnce();
  const html = popup.document.write.mock.calls[0][0] as string;
  expect(html).toContain('size:A5'); expect(html).toContain('客户甲'); expect(html).toContain('账单另附'); expect(html).toContain('9.4');
  expect(html).toContain(renderQrSvg(`${window.location.origin}/d/${token}`)); expect(html).toContain('加工来源');
  expect(openDelivery).toHaveBeenCalledTimes(2); expect(popup.opener).toBeNull();
  view.unmount(); vi.restoreAllMocks();
});
